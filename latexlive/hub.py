"""The hub: one port (--port, 44100 by default) for every preview on the machine.

Each preview still runs in its own process, with its own latexmk, terminal and port (from --port + 1);
the one holding HUB_LOCK also serves the hub, which forwards /p/<paper id>/<doc>/... to that preview.
When it exits, another preview takes over the lock and the same port within a second (once the port is
free; it waits while another program holds it), so viewer URLs keep working; the last one to exit closes
it."""

